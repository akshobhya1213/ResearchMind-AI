"""UI-independent handler logic (returns plain Python / pandas objects) so it can be unit-tested without Gradio."""
from __future__ import annotations

import logging
import re
import traceback
from pathlib import Path

import pandas as pd

from analysis import Comparator, GapAnalyzer, Summarizer
from config import CATEGORIES
from deep_learning.classifier import load_seed_dataset
from document_processing.errors import DuplicateDocumentError, ExtractionError, PDFValidationError
from evaluation import run_generation_eval, run_retrieval_comparison
from rag.llm import LLMError

log = logging.getLogger(__name__)
AI_LABEL = "> **AI-generated content.** Verify against the cited passages before relying on it."


def _md_cites(text: str) -> str:
    return text


def friendly_error(exc: Exception) -> str:
    if isinstance(exc, (PDFValidationError, DuplicateDocumentError, ValueError)):
        return f"{exc}"
    if isinstance(exc, LLMError):
        return f"LLM error: {exc}"
    log.error("Unhandled error: %s", traceback.format_exc())
    return f"Unexpected error ({type(exc).__name__}): {exc}"


class Handlers:
    def __init__(self, ctx):
        self.ctx = ctx
        self.summarizer, self.comparator, self.gaps = Summarizer(ctx), Comparator(ctx), GapAnalyzer(ctx)

    # ---- helpers
    def doc_choices(self) -> list[tuple[str, str]]:
        return [(f"{r['title'][:70]}  [{r['filename']}]", r["doc_id"]) for r in self.ctx.library.list()]

    def library_table(self) -> pd.DataFrame:
        rows = []
        for r in self.ctx.library.list():
            c = r.get("analysis", {}).get("classification")
            rows.append({"Title": r["title"], "File": r["filename"], "Pages": r["num_pages"], "Words": r["n_words"],
                         "Category": c["label"] if c else "-", "Confidence": round(c["confidence"], 3) if c else None,
                         "OCR pages": len(r.get("metadata", {}).get("ocr_pages", [])), "Added": r["added_at"], "ID": r["doc_id"]})
        return pd.DataFrame(rows, columns=["Title", "File", "Pages", "Words", "Category", "Confidence", "OCR pages", "Added", "ID"])

    # ---- dashboard
    def dashboard(self):
        st = self.ctx.status()
        lines = [f"- **Documents:** {st['documents']}   **Chunks:** {st['chunks']}   **Vector backend:** {st['vector_backend']}",
                 f"- **Embedder:** {st['embedder']}", f"- **Reranker:** {st['reranker']}", f"- **LLM:** {st['llm']}",
                 f"- **spaCy NER available:** {st['spacy_ner']}"]
        if "LEXICAL FALLBACK" in st["embedder"]:
            lines.append("- :warning: **A lexical fallback embedder is active: semantic search quality is reduced. Check model downloads.**")
        counts = {c: 0 for c in CATEGORIES}
        for r in self.ctx.library.list():
            c = r.get("analysis", {}).get("classification")
            if c:
                counts[c["label"]] = counts.get(c["label"], 0) + 1
        return "\n".join(lines), pd.DataFrame({"Category": list(counts), "Papers": list(counts.values())})

    # ---- upload
    def upload(self, files, progress=None):
        rows = []
        files = files or []
        for i, f in enumerate(files):
            path = Path(getattr(f, "name", f))
            if progress:
                progress((i, len(files)), desc=f"Processing {path.name}")
            try:
                rec = self.ctx.ingest_pdf(path)
                c = rec.get("analysis", {}).get("classification")
                rows.append({"File": path.name, "Status": "indexed", "Detail": f"{rec['num_pages']} pages, {rec['n_words']} words" + (f", category: {c['label']}" if c else "")})
            except Exception as exc:
                rows.append({"File": path.name, "Status": "rejected" if isinstance(exc, (PDFValidationError, DuplicateDocumentError, ExtractionError)) else "error", "Detail": friendly_error(exc)})
        return pd.DataFrame(rows, columns=["File", "Status", "Detail"])

    def delete(self, doc_id):
        if not doc_id:
            return "Select a document first."
        self.ctx.delete_document(doc_id)
        return "Document removed."

    def reindex(self):
        try:
            return f"Re-indexed {self.ctx.reindex()} chunks."
        except Exception as exc:
            return friendly_error(exc)

    # ---- summarization
    def summarize(self, doc_id, force=False):
        if not doc_id:
            return "Select a paper.", pd.DataFrame()
        try:
            res = self.summarizer.summarize(doc_id, force)
        except Exception as exc:
            return friendly_error(exc), pd.DataFrame()
        parts = [f"## {res['title']}", AI_LABEL, f"*Generated by: {res['generated_by']}*", ""]
        for k, v in res["fields"].items():
            parts.append(f"**{k.replace('_', ' ').title()}**\n\n{v}\n")
        src = pd.DataFrame([{"[n]": s["id"], "Pages": s["pages"], "Passage": s["text"][:300] + "..."} for s in res["sources"]])
        return "\n".join(parts), src

    # ---- Q&A
    def ask(self, question, doc_ids, mode, top_k, rerank):
        if not (question or "").strip():
            return "Enter a question.", pd.DataFrame(), pd.DataFrame()
        if not self.ctx.library.list():
            return "Upload at least one paper first.", pd.DataFrame(), pd.DataFrame()
        try:
            a = self.ctx.ask(question, doc_ids, mode, int(top_k), bool(rerank))
        except Exception as exc:
            return friendly_error(exc), pd.DataFrame(), pd.DataFrame()
        body = f"{AI_LABEL}\n\n{a.answer}\n\n*Generated by: {a.generated_by} · retrieval: {a.mode} · {a.elapsed_s:.1f}s*"
        if a.invalid_citations:
            body += f"\n\n:warning: The model cited non-existent passages {a.invalid_citations}; ignore those markers."
        cites = pd.DataFrame([{"[n]": s.id, "Paper": s.title, "File": s.filename, "Pages": s.page_label} for s in (a.cited_sources or a.sources)])
        ret = pd.DataFrame([{"Rank": r.rank, "Paper": r.chunk.doc_title[:50], "Pages": r.chunk.page_label, "Cosine": round(r.vector_score, 3),
                             "BM25": round(r.bm25_score, 2), "Rerank": None if r.rerank_score is None else round(r.rerank_score, 3),
                             "Passage": r.chunk.text[:260] + "..."} for r in a.retrieved])
        return body, cites, ret

    # ---- comparison / gaps
    def compare(self, doc_ids):
        try:
            res = self.comparator.compare(doc_ids or [])
        except Exception as exc:
            return pd.DataFrame(), friendly_error(exc)
        notes = "\n".join(f"- {n}" for n in res["comparability_notes"]) or "- No comparability warnings."
        return res["table"], f"{AI_LABEL}\n\n### Comparability checks (rule-based)\n{notes}\n\n### Explanation\n{res['explanation']}\n\n*Generated by: {res['generated_by']}*"

    def gap_analysis(self, doc_ids):
        try:
            res = self.gaps.analyze(doc_ids or [])
        except Exception as exc:
            return friendly_error(exc), pd.DataFrame(), pd.DataFrame()
        src = {s["id"]: s for s in res["sources"]}
        md = ["### Author-stated limitations and future work (verbatim evidence)"]
        for ev in res["author_stated_evidence"]:
            md.append(f"**{ev['title']}**")
            for i in ev["limitation_passages"][:1] + ev["future_work_passages"][:1]:
                md.append(f"- [{i}] ({src[i]['pages']}) {src[i]['text'][:350]}...")
        md.append("\n### Potential research gaps (hypotheses, not verified)\n" + AI_LABEL)
        if res["potential_gaps"]:
            for k, items in res["potential_gaps"].items():
                md.append(f"**{k.replace('_', ' ').title()}**\n" + ("\n".join(f"- {x}" for x in items) or "- (none reported)"))
        else:
            md.append(res.get("potential_gaps_note", ""))
        md.append(f"\n### Verified literature gaps\n{res['verified_note']}")
        return "\n".join(md), res["keyword_table"], res["method_table"]

    # ---- NLP & classification
    def nlp_view(self, doc_id):
        empty = pd.DataFrame()
        if not doc_id:
            return {}, empty, empty, "Select a paper."
        rec = self.ctx.library.get(doc_id)
        an = rec.get("analysis", {})
        cls = an.get("classification")
        if cls is None:
            try:
                cls = self.ctx.classify_document(self.ctx.library.get_document(doc_id))
                self.ctx.library.set_analysis(doc_id, "classification", cls)
            except Exception as exc:
                return {}, empty, empty, friendly_error(exc)
        kw = pd.DataFrame(an.get("keywords", []), columns=["Keyword", "TF-IDF score"])
        ent = pd.DataFrame([{"Type": k, "Entity": e, "Count": c} for k, v in an.get("entities", {}).items() for e, c in v])
        info = f"Classifier: logistic regression on `{cls['model']}` embeddings. Confidence = predicted probability (uncalibrated; categories overlap)."
        return {k: float(v) for k, v in list(cls["scores"].items())[:5]}, kw, ent, info

    def classifier_metrics(self):
        try:
            texts, labels = load_seed_dataset()
            rep = self.ctx.get_classifier().cross_validate(texts, labels)
        except Exception as exc:
            return pd.DataFrame(), friendly_error(exc)
        rows = [{"Class": k, "Precision": round(v["precision"], 3), "Recall": round(v["recall"], 3), "F1": round(v["f1-score"], 3), "Support": int(v["support"])}
                for k, v in rep.items() if isinstance(v, dict) and "precision" in v]
        m = rep["_meta"]
        return pd.DataFrame(rows), (f"{m['folds']}-fold stratified cross-validation on {m['n_samples']} hand-written seed abstracts "
                                    f"(embedder: {m['embedder']}). Small dataset: indicative only.")

    # ---- evaluation
    def run_eval(self, with_generation, progress=None):
        try:
            emb, rr = self.ctx.get_embedder(), self.ctx.get_reranker()
            res = run_retrieval_comparison(emb, rr, save_to=self.ctx.settings.eval_dir / "retrieval_results.json")
            df = pd.DataFrame(res["rows"])
            note = (f"Measured on {res['n_questions']} questions / {res['n_chunks']} chunks. Embedder: `{res['embedder']}` "
                    f"({'transformer' if res['embedder_is_transformer'] else 'LEXICAL FALLBACK'}); reranker: `{res['reranker']}`. {res['caveat']}")
            if with_generation:
                llm = self.ctx.get_llm()
                if llm is None:
                    note += "\n\nGeneration metrics skipped: no LLM configured."
                else:
                    g = run_generation_eval(emb, rr, llm, save_to=self.ctx.settings.eval_dir / "generation_results.json")
                    note += (f"\n\n**Generation ({g['llm']}):** faithfulness (LLM judge) = {g['faithfulness_llm_judge']}, answer relevancy (embedding proxy) = "
                             f"{g['answer_relevancy_proxy']}, answer similarity = {g['answer_similarity']}, abstention on unanswerable = {g['abstention_rate_on_unanswerable']}")
            return df, note
        except Exception as exc:
            return pd.DataFrame(), friendly_error(exc)

    # ---- settings
    def apply_settings(self, chunk_size, overlap, top_k, min_vec, min_rr):
        s = self.ctx.settings
        if int(overlap) >= int(chunk_size):
            return "Overlap must be smaller than chunk size."
        changed_chunking = (s.chunk_size, s.chunk_overlap) != (int(chunk_size), int(overlap))
        s.chunk_size, s.chunk_overlap, s.top_k = int(chunk_size), int(overlap), int(top_k)
        s.min_vector_score, s.min_rerank_score = float(min_vec), float(min_rr)
        self.ctx.apply_retrieval_params(top_k=s.top_k, min_vector_score=s.min_vector_score, min_rerank_score=s.min_rerank_score)
        return "Settings applied." + (" Chunking changed: click 'Re-index all documents' to apply it to existing papers." if changed_chunking else "")
